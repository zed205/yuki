import { type JSX, splitProps } from 'solid-js';
import { cn } from '../../lib/utils';

export interface IconButtonProps extends JSX.ButtonHTMLAttributes<HTMLButtonElement> {
  icon?: string;
  variant?: 'default' | 'ghost' | 'outline';
  size?: 'sm' | 'md';
  tooltip?: string;
}

export function IconButton(props: IconButtonProps) {
  const {
    class: className,
    icon,
    variant = 'ghost',
    size = 'md',
    tooltip,
    ...rest
  } = props;
  const [local, others] = splitProps(rest, ['class']);

  const variantClasses = {
    default: 'bg-[hsl(var(--secondary))] text-foreground hover:bg-[hsl(var(--secondary))/80]',
    ghost: 'hover:bg-[hsl(var(--secondary))] text-foreground hover:text-text',
    outline: 'border border-[hsl(var(--border))] bg-transparent hover:bg-[hsl(var(--secondary))]',
  };

  const sizeClasses = {
    sm: 'h-7 w-7',
    md: 'h-8 w-8',
  };

  const iconMap: Record<string, JSX.Element> = {
    menu: <MenuIcon />,
    x: <XIcon />,
    plus: <PlusIcon />,
    settings: <SettingsIcon />,
    search: <SearchIcon />,
    mic: <MicIcon />,
    micOff: <MicOffIcon />,
    send: <SendIcon />,
    stop: <SquareIcon />,
    chevronDown: <ChevronDownIcon />,
    chevronRight: <ChevronRightIcon />,
    chevronUp: <ChevronUpIcon />,
    moreHorizontal: <MoreHorizontalIcon />,
    folder: <FolderIcon />,
    folderOpen: <FolderOpenIcon />,
    trash: <TrashIcon />,
    copy: <CopyIcon />,
    edit: <PencilIcon />,
    play: <PlayIcon />,
    pause: <PauseIcon />,
  };

  const renderIcon = () => {
    if (icon && icon in iconMap) {
      return iconMap[icon as keyof typeof iconMap];
    }
    return icon;
  };

  return (
    <button
      type="button"
      title={tooltip}
      class={cn(
        'inline-flex items-center justify-center rounded-md transition-colors',
        'text-muted-foreground hover:text-foreground',
        variantClasses[variant],
        sizeClasses[size],
        local.class,
        className
      )}
      {...others}
    >
      {renderIcon()}
    </button>
  );
}

